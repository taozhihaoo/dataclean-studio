def write_csv(path: Path, columns: list[str], rows: list[tuple]) -> None:
    frame = pd.DataFrame(rows, columns=columns).fillna("")
    path.write_text(frame.to_csv(index=False, lineterminator="\n"), encoding="utf-8")
    print(f"wrote {path} ({len(rows)} rows)")


def main() -> None:
    DEMO_DIR.mkdir(parents=True, exist_ok=True)
    write_csv(DEMO_DIR / "sample_customers.csv", CUSTOMER_COLUMNS, CUSTOMERS)
    write_csv(DEMO_DIR / "sample_orders.csv", ORDER_COLUMNS, ORDERS)
    write_csv(DEMO_DIR / "sample_customers_new_batch.csv", NEW_BATCH_COLUMNS, NEW_BATCH)

    frame = pd.DataFrame(CUSTOMERS, columns=CUSTOMER_COLUMNS).fillna("")
    frame.to_excel(DEMO_DIR / "sample_customers.xlsx", index=False, sheet_name="Customers")
    print(f"wrote {DEMO_DIR / 'sample_customers.xlsx'}")


if __name__ == "__main__":
    main()
